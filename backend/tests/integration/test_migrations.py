"""Integration tests for migration state, drift, and reversibility."""

from __future__ import annotations

import os
import uuid
from collections.abc import Iterator
from contextlib import contextmanager

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url

from tests.conftest import BACKEND_ROOT, requires_postgres

pytestmark = requires_postgres


def _alembic_config() -> Config:
    config = Config(str(BACKEND_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_ROOT / "migrations"))
    return config


@contextmanager
def _migrating(database_url: str) -> Iterator[Config]:
    """Run alembic against the given database and restore the environment."""
    previous = os.environ.get("DATABASE_URL")
    os.environ["DATABASE_URL"] = database_url
    try:
        yield _alembic_config()
    finally:
        if previous is None:
            os.environ.pop("DATABASE_URL", None)
        else:
            os.environ["DATABASE_URL"] = previous


@pytest.fixture()
def scratch_database_url(database_url: str) -> Iterator[str]:
    """A brand-new empty database, dropped after the test."""
    admin_url = make_url(database_url).set(database="postgres")
    name = f"openseat_migrate_{uuid.uuid4().hex[:10]}"
    engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with engine.connect() as connection:
        connection.execute(text(f'CREATE DATABASE "{name}"'))
    engine.dispose()

    scratch_url = make_url(database_url).set(database=name).render_as_string(
        hide_password=False,
    )
    try:
        yield scratch_url
    finally:
        engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
        with engine.connect() as connection:
            connection.execute(text(f'DROP DATABASE "{name}" WITH (FORCE)'))
        engine.dispose()


def _tables(database_url: str) -> set[str]:
    engine = create_engine(database_url)
    with engine.connect() as connection:
        rows = connection.execute(
            text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'"),
        ).fetchall()
    engine.dispose()
    return {row[0] for row in rows}


def _revision(database_url: str) -> str | None:
    engine = create_engine(database_url)
    with engine.connect() as connection:
        revision = connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
    engine.dispose()
    return revision


def test_upgrade_from_an_empty_database_reaches_head(scratch_database_url: str) -> None:
    with _migrating(scratch_database_url) as config:
        # A newly created database starts empty, so migrations are the only
        # thing that can create the schema.
        assert _tables(scratch_database_url) == set()
        command.upgrade(config, "head")
        head = ScriptDirectory.from_config(config).get_current_head()

    assert {"users", "sessions", "bookings"} <= _tables(scratch_database_url)
    assert _revision(scratch_database_url) == head


def test_latest_revision_downgrades_one_step_and_upgrades_again(
    scratch_database_url: str,
) -> None:
    with _migrating(scratch_database_url) as config:
        command.upgrade(config, "head")
        head = ScriptDirectory.from_config(config).get_current_head()

        command.downgrade(config, "-1")
        # The latest revision owns the bookings table.
        assert "bookings" not in _tables(scratch_database_url)
        assert "sessions" in _tables(scratch_database_url)

        command.upgrade(config, "head")

    assert _tables(scratch_database_url) >= {"users", "sessions", "bookings"}
    assert _revision(scratch_database_url) == head


def test_alembic_check_reports_no_pending_model_changes(scratch_database_url: str) -> None:
    with _migrating(scratch_database_url) as config:
        command.upgrade(config, "head")
        # Raises AutogenerateDiffsDetected when models and schema disagree.
        command.check(config)
